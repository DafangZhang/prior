import "strings"

// chinese is true while the interface shows in Simplified Chinese.
var chinese = true

// setLanguage chooses the language: "en", "zh", or the locale's with
// anything else, as "system".
func setLanguage(language, locale string) {
	switch language {
	case "en":
		chinese = false
	case "zh":
		chinese = true
	default:
		chinese = strings.HasPrefix(strings.ToLower(locale), "zh")
	}
}

// T returns s in the language of the interface. English texts are their
// own keys, so a text without a translation shows as written.
func T(s string) string {
	if chinese {
		if zh, ok := zhCN[s]; ok {
			return zh
		}
	}
	return s
}

